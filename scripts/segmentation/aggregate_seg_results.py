"""Aggregate the five per-dose eval CSVs into the paper's segmentation results table.

Reads paper/tables/nnunet_eval/{internal,lumiere}_synth{0,500,1000,5000,10000}.csv,
computes cohort mean and 95% bootstrap CI per (region, metric, dose, split), and
emits paper/tables/nnunet_seg_results.tex + a matching CSV.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import pandas as pd

REGIONS = ("WT", "TC", "ET")
METRICS = ("Dice", "HD95")
DOSES = (0, 500, 1000, 5000, 10000)
SPLITS = ("internal", "lumiere")


def _boot_ci(x: np.ndarray, n_boot: int = 2000, seed: int = 0) -> tuple[float, float]:
    rng = np.random.default_rng(seed)
    idx = rng.integers(0, len(x), size=(n_boot, len(x)))
    means = x[idx].mean(axis=1)
    return float(np.percentile(means, 2.5)), float(np.percentile(means, 97.5))


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--in-dir", type=Path, default=Path("paper/tables/nnunet_eval"))
    ap.add_argument("--out-tex", type=Path, default=Path("paper/tables/nnunet_seg_results.tex"))
    ap.add_argument("--out-csv", type=Path, default=Path("paper/tables/nnunet_seg_results.csv"))
    args = ap.parse_args()

    records = []
    for split in SPLITS:
        for dose in DOSES:
            f = args.in_dir / f"{split}_synth{dose}.csv"
            if not f.is_file():
                print(f"[skip] missing {f}")
                continue
            df = pd.read_csv(f)
            for region in REGIONS:
                for metric in METRICS:
                    col = f"{region}_{metric}"
                    if col not in df:
                        continue
                    vals = df[col].to_numpy(dtype=float)
                    lo, hi = _boot_ci(vals)
                    records.append({
                        "split": split, "n_synth": dose, "region": region,
                        "metric": metric, "n": len(vals),
                        "mean": float(vals.mean()), "std": float(vals.std()),
                        "ci_lo": lo, "ci_hi": hi,
                    })
    out = pd.DataFrame.from_records(records)
    args.out_csv.parent.mkdir(parents=True, exist_ok=True)
    out.to_csv(args.out_csv, index=False)

    # LaTeX: one panel per split, rows = region x metric, cols = dose.
    lines = [
        r"% Auto-generated by scripts/segmentation/aggregate_seg_results.py",
        r"\begin{table}[!t]",
        r"  \centering",
        r"  \caption{Lesion-wise segmentation performance vs.\ synthetic augmentation dose. Dice (higher is better) and HD95 in mm (lower is better) are reported per BraTS region with 95\% bootstrap CI over cases. WT = whole tumor (1+2+3); TC = tumor core (1+3); ET = enhancing tumor (3). Small-lesion threshold 50 voxels (BraTS 2024 protocol).}",
        r"  \label{tab:seg_results}",
        r"  \small",
        r"  \begin{tabular}{@{}llrrrrr@{}}",
        r"    \toprule",
        r"    Split & Region/Metric & \multicolumn{5}{c}{$n_{\text{synth}}$} \\",
        r"    \cmidrule(lr){3-7}",
        r"     &  & 0 & 500 & 1{,}000 & 5{,}000 & 10{,}000 \\",
        r"    \midrule",
    ]
    for split in SPLITS:
        first_row = True
        for region in REGIONS:
            for metric in METRICS:
                cells = []
                for dose in DOSES:
                    sub = out[(out.split == split) & (out.region == region) &
                              (out.metric == metric) & (out.n_synth == dose)]
                    if sub.empty:
                        cells.append("--")
                    else:
                        m = sub.iloc[0]
                        cells.append(f"{m['mean']:.3f} [{m['ci_lo']:.3f}, {m['ci_hi']:.3f}]")
                label = f"{region} {metric}"
                prefix = split.upper() if first_row else ""
                lines.append(f"    {prefix} & {label} & " + " & ".join(cells) + r" \\")
                first_row = False
        lines.append(r"    \midrule")
    lines[-1] = r"    \bottomrule"
    lines += [r"  \end{tabular}", r"\end{table}", ""]
    args.out_tex.write_text("\n".join(lines))
    print(f"[wrote] {args.out_csv} and {args.out_tex}")


if __name__ == "__main__":
    main()
